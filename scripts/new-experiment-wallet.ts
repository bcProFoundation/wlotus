#!/usr/bin/env tsx
/**
 * Generate a fresh THROWAWAY experiment keypair for the multi-input
 * (two-shard M+C) dogfood experiment and print funding addresses.
 *
 * - Writes `.env` (gitignored, mode 0600) ONLY if it does not exist.
 *   Never overwrites an existing `.env` — pass --force to rotate.
 * - Writes `deployments/pending-multiinput-funding.json` with ADDRESSES
 *   ONLY (no secrets — safe to commit in the PR so the funder can see it).
 * - Makes zero network calls: pure offline keygen + address derivation.
 *   Fund on mainnet (XEC) for dogfood, or on testnet (tXEC via the
 *   texplorer faucet) once a reachable testnet Chronik is configured
 *   via CHRONIK_URLS.
 */
import { randomBytes } from 'node:crypto';
import { writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { ChronikClient } from 'chronik-client';
import { Wallet } from 'ecash-wallet';
import { toHex } from 'ecash-lib';
import { MAINNET_CHRONIK_URLS } from '../src/network/chronikUrls.js';

async function main(): Promise<void> {
  const force = process.argv.includes('--force');
  const envPath = resolve(process.cwd(), '.env');
  if (existsSync(envPath) && !force) {
    console.error(
      `.env already exists. Pass --force to rotate the experiment key, or fund the address in deployments/pending-multiinput-funding.json.`,
    );
    process.exit(1);
  }

  // No network I/O: constructor only stores URLs (no latency probe,
  // unlike ChronikClient.useStrategy). Do NOT call wallet.sync() here.
  const chronik = new ChronikClient([...MAINNET_CHRONIK_URLS]);
  const sk = randomBytes(32);
  const mainnet = Wallet.fromSk(sk, chronik);
  const testnet = Wallet.fromSk(sk, chronik, { prefix: 'ectest' });

  const body = [
    '# Generated by npm run new-experiment-wallet — DO NOT COMMIT',
    '# THROWAWAY experiment key: fund small amounts only, sweep when done.',
    `CHRONIK_URL=${MAINNET_CHRONIK_URLS[0]}`,
    `GENESIS_SK_HEX=${toHex(sk)}`,
    `GENESIS_ADDRESS=${mainnet.address}`,
    `EXPERIMENT_ECTEST_ADDRESS=${testnet.address}`,
    '',
  ].join('\n');
  writeFileSync(envPath, body, { mode: 0o600 });

  const pending = {
    network: 'mainnet-dogfood (or ectest testnet via faucet)',
    experiment: 'multi-input two-shard (M+C) K=3 prototype',
    research: 'docs/research/glotus-ergon-multiinput-daa.md',
    mainnetAddress: mainnet.address,
    testnetAddress: testnet.address,
    testnetFaucet: 'https://texplorer.e.cash/testnet-faucet',
    suggestedXec: 50,
    why: 'ALP genesis (2 batons: M+C shards) + 2 handoffs + remint/tick fees; dust=546 sats, fee=1000 sats/kB — 50 XEC is a generous buffer, unspent funds sweepable',
    nextStep: 'Fund mainnetAddress, then: prototype shards → genesis → mine-and-mint',
    chronikUrls: [...MAINNET_CHRONIK_URLS],
    warning:
      'Throwaway key — the SK lives in VM .env (gitignored, never committed). Do not reuse for real funds.',
  };
  writeFileSync(
    resolve(process.cwd(), 'deployments/pending-multiinput-funding.json'),
    `${JSON.stringify(pending, null, 2)}\n`,
  );

  console.log(JSON.stringify(pending, null, 2));
  console.log(`\nWrote ${envPath} (gitignored) and deployments/pending-multiinput-funding.json`);
}

main().catch(err => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
